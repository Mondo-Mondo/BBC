let currentLang = localStorage.getItem('bbc-lang') || 'en';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('bbc-lang', lang);

  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[lang] && translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  document.querySelectorAll('.lang-en, .lang-fr').forEach(el => {
    el.classList.toggle('active', el.classList.contains(`lang-${lang}`));
  });
}

document.addEventListener('DOMContentLoaded', () => {

  setLanguage(currentLang);

  // ===== LANGUAGE TOGGLE =====
  const langToggle = document.getElementById('langToggle');
  if (langToggle) {
    langToggle.addEventListener('click', () => {
      const newLang = currentLang === 'en' ? 'fr' : 'en';
      setLanguage(newLang);
    });
  }

  // ===== NAVBAR SCROLL EFFECT =====
  const navbar = document.querySelector('.navbar');

  window.addEventListener('scroll', () => {
    navbar.classList.toggle('scrolled', window.scrollY > 50);
  });

  // ===== MOBILE MENU =====
  const hamburger = document.querySelector('.hamburger');
  const navMenu = document.querySelector('.nav-menu');

  hamburger.addEventListener('click', () => {
    hamburger.classList.toggle('active');
    navMenu.classList.toggle('active');
  });

  document.querySelectorAll('.nav-link').forEach(link => {
    link.addEventListener('click', () => {
      hamburger.classList.remove('active');
      navMenu.classList.remove('active');
    });
  });

  // ===== SMOOTH SCROLL =====
  window.scrollToSection = (sectionId) => {
    const section = document.getElementById(sectionId);
    if (section) {
      section.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  };

  // ===== SCROLL REVEAL ANIMATIONS =====
  const revealElements = document.querySelectorAll('.service-card, .usecase-card, .process-step, .slide, .stat-card, .about-text, .about-image, .contact-form');

  const revealObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry, index) => {
      if (entry.isIntersecting) {
        setTimeout(() => {
          entry.target.classList.add('reveal', 'visible');
        }, index * 80);
        revealObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.1, rootMargin: '0px 0px -50px 0px' });

  revealElements.forEach(el => revealObserver.observe(el));

  // ===== ANIMATED COUNTERS =====
  const counters = document.querySelectorAll('.stat-number');
  let countersAnimated = false;

  const counterObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting && !countersAnimated) {
        countersAnimated = true;
        animateCounters();
        counterObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.5 });

  const statsGrid = document.querySelector('.stats-grid');
  if (statsGrid) counterObserver.observe(statsGrid);

  function animateCounters() {
    counters.forEach(counter => {
      const text = counter.textContent;
      const numericMatch = text.match(/(\d+)\+?/);
      if (!numericMatch) return;

      const target = parseInt(numericMatch[1]);
      const suffix = text.includes('+') ? '+' : '';
      const duration = 2000;
      const startTime = performance.now();

      function update(currentTime) {
        const elapsed = currentTime - startTime;
        const progress = Math.min(elapsed / duration, 1);
        const eased = 1 - Math.pow(1 - progress, 3);
        const current = Math.floor(eased * target);
        counter.textContent = current + suffix;

        if (progress < 1) {
          requestAnimationFrame(update);
        } else {
          counter.textContent = target + suffix;
        }
      }

      requestAnimationFrame(update);
    });
  }

  // ===== CLIENT SLIDER =====
  const track = document.getElementById('sliderTrack');
  const dotsContainer = document.getElementById('sliderDots');
  const prevBtn = document.querySelector('.slider-prev');
  const nextBtn = document.querySelector('.slider-next');

  if (track && dotsContainer) {
    const slides = track.querySelectorAll('.slide');
    let currentIndex = 0;
    let slidesPerView = getSlidesPerView();
    const totalSlides = slides.length;

    slides.forEach((_, i) => {
      const dot = document.createElement('button');
      dot.className = `dot${i === 0 ? ' active' : ''}`;
      dot.setAttribute('aria-label', `Slide ${i + 1}`);
      dot.addEventListener('click', () => goToSlide(i));
      dotsContainer.appendChild(dot);
    });

    function getSlidesPerView() {
      if (window.innerWidth < 480) return 1;
      if (window.innerWidth < 768) return 2;
      if (window.innerWidth < 1024) return 3;
      return 4;
    }

    function getSlideWidth() {
      if (slides.length === 0) return 220;
      const containerWidth = track.parentElement.offsetWidth - 100;
      const gap = window.innerWidth < 768 ? 12 : 20;
      const spv = getSlidesPerView();
      return (containerWidth - (spv - 1) * gap) / spv;
    }

    function updateSlider() {
      const slideWidth = getSlideWidth();
      const gap = window.innerWidth < 768 ? 12 : 20;
      const offset = -(currentIndex * (slideWidth + gap));

      slides.forEach(s => {
        s.style.minWidth = `${slideWidth}px`;
      });

      track.style.transform = `translateX(${offset}px)`;

      document.querySelectorAll('.slider-dots .dot').forEach((dot, i) => {
        dot.classList.toggle('active', i === currentIndex);
      });

      if (prevBtn) prevBtn.style.display = currentIndex === 0 ? 'none' : 'flex';
      if (nextBtn) nextBtn.style.display = currentIndex >= totalSlides - getSlidesPerView() ? 'none' : 'flex';
    }

    function goToSlide(index) {
      const maxIndex = Math.max(0, totalSlides - getSlidesPerView());
      currentIndex = Math.min(index, maxIndex);
      updateSlider();
    }

    function nextSlide() {
      goToSlide(currentIndex + 1);
    }

    function prevSlide() {
      goToSlide(currentIndex - 1);
    }

    if (prevBtn) prevBtn.addEventListener('click', prevSlide);
    if (nextBtn) nextBtn.addEventListener('click', nextSlide);

    let autoSlide = setInterval(nextSlide, 4000);

    track.addEventListener('mouseenter', () => clearInterval(autoSlide));
    track.addEventListener('mouseleave', () => {
      clearInterval(autoSlide);
      autoSlide = setInterval(nextSlide, 4000);
    });

    window.addEventListener('resize', () => {
      const spv = getSlidesPerView();
      const maxIndex = Math.max(0, totalSlides - spv);
      if (currentIndex > maxIndex) currentIndex = maxIndex;
      updateSlider();
    });

    updateSlider();
  }

  // ===== CONTACT FORM =====
  const contactForm = document.getElementById('contactForm');

  if (contactForm) {
    contactForm.addEventListener('submit', (e) => {
      e.preventDefault();

      const btn = contactForm.querySelector('.btn');
      const originalHTML = btn.innerHTML;

      btn.innerHTML = translations[currentLang]['toast-sending'];
      btn.disabled = true;

      setTimeout(() => {
        showToast(translations[currentLang]['toast-success']);
        contactForm.reset();
        btn.innerHTML = originalHTML;
        btn.disabled = false;
      }, 1500);
    });
  }

  // ===== TOAST NOTIFICATION =====
  function showToast(message) {
    const existing = document.querySelector('.toast');
    if (existing) existing.remove();

    const toast = document.createElement('div');
    toast.className = 'toast';
    toast.textContent = message;
    document.body.appendChild(toast);

    requestAnimationFrame(() => {
      toast.classList.add('show');
    });

    setTimeout(() => {
      toast.classList.remove('show');
      setTimeout(() => toast.remove(), 300);
    }, 4000);
  }

  // ===== PARALLAX FLOATING ELEMENTS =====
  document.querySelectorAll('.floating-element').forEach((el, index) => {
    const speed = 0.02 + (index * 0.01);
    let x = 0, y = 0;

    document.addEventListener('mousemove', (e) => {
      const rect = el.getBoundingClientRect();
      const centerX = rect.left + rect.width / 2;
      const centerY = rect.top + rect.height / 2;
      const deltaX = (e.clientX - centerX) * speed;
      const deltaY = (e.clientY - centerY) * speed;

      x += (deltaX - x) * 0.05;
      y += (deltaY - y) * 0.05;

      el.style.transform = `translate(${x}px, ${y}px)`;
    });
  });

});
